import Metal
import simd

/// A patch's name: level, base face, and path (one child index, 0...3, per level).
typealias PatchKey = pl_patch_key

/// What the camera sees, for choosing patches.
struct PatchView {
    var viewProjection: simd_float4x4
    var camera: SIMD3<Float>
    var pixelsPerRadian: Float
}

/// A patch to draw: its vertices and the vertex shader's constants (skirt depth and the
/// parent's triangle edge, in radii).
struct PatchDraw {
    var buffer: MTLBuffer
    var constants: SIMD2<Float>
}

/// The patches' vertex buffers, by the core's slot: the storage the core's level of detail
/// borrows (`pl_lod_storage`), acquired and released only during its calls on the main thread.
private final class PatchBuffers {
    let device: MTLDevice
    var buffers: [MTLBuffer?] = []

    init(device: MTLDevice) {
        self.device = device
    }

    var storage: pl_lod_storage {
        pl_lod_storage(
            context: Unmanaged.passUnretained(self).toOpaque(),
            acquire: { context, slot in
                let self_ = Unmanaged<PatchBuffers>.fromOpaque(context!).takeUnretainedValue()
                let length = Int(pl_patch_vertex_count()) * 12 * MemoryLayout<Float>.stride
                guard let buffer = self_.device.makeBuffer(length: length, options: .storageModeShared)
                else { return nil }
                let slot = Int(slot)
                if slot >= self_.buffers.count {
                    self_.buffers.append(contentsOf: repeatElement(nil, count: slot + 1 - self_.buffers.count))
                }
                self_.buffers[slot] = buffer
                return buffer.contents().assumingMemoryBound(to: Float.self)
            },
            release: { context, slot in
                Unmanaged<PatchBuffers>.fromOpaque(context!).takeUnretainedValue().buffers[Int(slot)] = nil
            }
        )
    }
}

/// The patches drawn each frame, chosen, cached, and (synchronously) generated by the core's
/// level of detail (`pl_lod_*`). Here: background generation of what it requests, at utility
/// priority, and the patches' Metal buffers.
@MainActor
final class PatchCache {
    let indexBuffer: MTLBuffer
    let surfaceIndexCount: Int
    let indexCount: Int
    /// Generate every missing patch before drawing (snapshots, benchmarks, and video).
    var synchronous = false

    /// Most bytes of patches kept; least recently used ones beyond this are evicted (on the next
    /// selection, so shrinking applies as soon as the view redraws).
    var capacityBytes = 40_000_000 {
        didSet { pl_lod_set_capacity_bytes(lod, UInt64(capacityBytes)) }
    }
    /// Triangle edge, in pixels, above which a patch is refined.
    var targetPixels: Float = 12 {
        didSet { pl_lod_set_detail(lod, targetPixels) }
    }
    /// Radii per meter of elevation, with exaggeration; changing it refits every cached patch.
    var scale: Float {
        didSet { if scale != oldValue { pl_lod_set_surface(lod, scale, seaLevel) } }
    }
    /// Sea level in meters; oceans sit at it, so changing it also refits every cached patch.
    var seaLevel: Float {
        didSet { if seaLevel != oldValue { pl_lod_set_surface(lod, scale, seaLevel) } }
    }

    private(set) var drawn = 0
    private var stats: pl_lod_stats { pl_lod_stats_get(lod) }
    /// Cached patches the last selection used (hits); generated ones were misses.
    var visited: Int { Int(stats.visited) }
    var generatedThisFrame: Int { Int(stats.generated) }
    var generationSeconds: Double { stats.generation_seconds }
    var cachedCount: Int { Int(stats.cached) }
    var cachedBytes: Int { Int(stats.cached_bytes) }

    private let planet: Planet
    private let buffers: PatchBuffers
    /// The core's level of detail; destroyed in `deinit`, when nothing else can reach it.
    nonisolated(unsafe) private let lod: OpaquePointer
    /// Leaves two cores for the main thread and the window server.
    private let maxInFlight = max(ProcessInfo.processInfo.activeProcessorCount - 2, 2)

    /// Called when a background patch arrives, so the view can draw it.
    var onInstall: (() -> Void)?

    init?(planet: Planet, device: MTLDevice, scale: Float, seaLevel: Float) {
        let indexCount = Int(pl_patch_index_count())
        var indices = [UInt32](repeating: 0, count: indexCount)
        pl_patch_indices(&indices)
        let buffers = PatchBuffers(device: device)
        var storage = buffers.storage
        guard let indexBuffer = device.makeBuffer(
            bytes: indices, length: indexCount * MemoryLayout<UInt32>.stride, options: .storageModeShared),
            let lod = planet.withHandle({ pl_lod_create($0, &storage, scale, seaLevel) })
        else { return nil }
        self.indexBuffer = indexBuffer
        self.indexCount = indexCount
        self.surfaceIndexCount = Int(pl_patch_surface_index_count())
        self.planet = planet
        self.buffers = buffers
        self.scale = scale
        self.seaLevel = seaLevel
        self.lod = lod
        pl_lod_set_capacity_bytes(lod, UInt64(capacityBytes))
    }

    deinit {
        pl_lod_destroy(lod)
    }

    /// Patches to draw for `view`, coarsest that look fine; starts generating missing ones, or,
    /// when synchronous, has the core generate them all first.
    func select(_ view: PatchView) -> [PatchDraw] {
        var camera = [view.camera.x, view.camera.y, view.camera.z]
        var matrix = view.viewProjection
        let selected = withUnsafeBytes(of: &matrix) {
            pl_lod_select(
                lod, $0.baseAddress!.assumingMemoryBound(to: Float.self), &camera, view.pixelsPerRadian,
                UInt32(maxInFlight), synchronous)
        }
        guard selected else { return [] }
        Self.items(pl_lod_requests, lod).forEach(request)
        let draws = Self.items(pl_lod_draws, lod).compactMap { draw in
            buffers.buffers[Int(draw.slot)].map {
                PatchDraw(buffer: $0, constants: SIMD2(draw.skirt_depth, draw.parent_edge))
            }
        }
        drawn = draws.count
        return draws
    }

    private func request(_ key: PatchKey) {
        let planet = planet
        Task.detached(priority: .utility) {
            var vertices = [Float](repeating: 0, count: Int(pl_patch_vertex_count()) * 12)
            planet.generatePatch(key, into: &vertices)
            await self.install(key, vertices)
        }
    }

    private func install(_ key: PatchKey, _ vertices: [Float]) {
        // On failure (no memory or storage), it's no longer pending, so it's requested again.
        if pl_lod_install(lod, key, vertices) >= 0 { onInstall?() }
    }

    /// One of the core's per-selection lists, copied out.
    private static func items<T>(
        _ list: (OpaquePointer?, UnsafeMutablePointer<UInt32>?) -> UnsafePointer<T>?, _ lod: OpaquePointer
    ) -> [T] {
        var count: UInt32 = 0
        guard let items = list(lod, &count) else { return [] }
        return Array(UnsafeBufferPointer(start: items, count: Int(count)))
    }
}
