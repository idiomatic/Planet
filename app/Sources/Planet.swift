import Foundation

/// Generation parameters: fixed once a planet is generated. (The live parameters are in
/// ViewValues.)
struct PlanetParameters: Equatable {
    var seed = ""
    var regionScale = 1.0

    var seedValue: UInt64 {
        let bytes = Array(seed.utf8)
        return bytes.withUnsafeBufferPointer { buffer in
            buffer.withMemoryRebound(to: CChar.self) { pl_seed_from_string($0.baseAddress, $0.count) }
        }
    }

    /// The core's parameters: exactly these, since everything else is the view's.
    var core: pl_params { pl_params(seed: seedValue, region_scale: regionScale) }
}

/// Owns a planet generated by the Zig core. Immutable once created, so it's shared with the
/// background threads that generate patches.
final class Planet: @unchecked Sendable {
    let parameters: PlanetParameters
    private let handle: OpaquePointer

    init?(_ parameters: PlanetParameters) {
        var params = parameters.core
        guard let handle = pl_planet_create(&params) else { return nil }
        self.parameters = parameters
        self.handle = handle
    }

    deinit {
        pl_planet_destroy(handle)
    }

    var vertexCount: Int { Int(pl_planet_vertex_count(handle)) }
    /// The coarse mesh's highest vertex, on the unit sphere.
    var peak: SIMD3<Float> {
        var out: (Float, Float, Float) = (0, 0, 0)
        withUnsafeMutablePointer(to: &out) {
            $0.withMemoryRebound(to: Float.self, capacity: 3) { pl_planet_peak(handle, $0) }
        }
        return SIMD3(out.0, out.1, out.2)
    }
    var minElevation: Float { pl_planet_min_elevation(handle) }
    var maxElevation: Float { pl_planet_max_elevation(handle) }

    /// The surface as `view` shows it: scale, sea level, floor, and the air's extent.
    func surface(_ view: ViewValues) -> pl_surface {
        pl_planet_surface(handle, view.exaggeration, view.seaLevel)
    }

    /// Writes the patch's vertices; `out` holds pl_patch_vertex_count() × 12 floats.
    func generatePatch(_ key: PatchKey, into out: inout [Float]) {
        pl_patch_generate(handle, key.level, key.face, key.path, &out)
    }
}
